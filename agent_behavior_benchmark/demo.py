from __future__ import annotations

import random
from pathlib import Path

from .environments import TrialResult, environment_from_name
from .providers import provider_from_name


def run_dialogue_demo(seed: int = 7) -> tuple[TrialResult, str]:
    """Run a deterministic, no-cost transcript for the repository walkthrough."""
    providers = [
        provider_from_name("openai_style", seed=seed),
        provider_from_name("claude_style", seed=seed),
    ]
    condition = {
        "condition_id": "dialogue_demo_aligned",
        "incentive_pressure": 0.5,
        "payoff_structure": "aligned",
        "opponent_information": "claims are verified against synthetic private state",
    }
    result = environment_from_name("negotiation_dialogue").run_trial(
        0,
        providers,
        random.Random(f"dialogue-demo:{seed}"),
        condition,
    )
    return result, render_dialogue_demo(result, seed)


def render_dialogue_demo(result: TrialResult, seed: int) -> str:
    lines = [
        "# Dialogue Negotiation Demo",
        "",
        "This transcript is generated by the deterministic scripted providers. It makes no API calls and is an illustration of the multi-turn protocol, not evidence about live models.",
        "",
        f"**Seed:** `{seed}`  ",
        f"**Synthetic total:** {result.public_state['total_value']}  ",
        f"**Reward structure:** {result.public_state['payoff_structure']}",
        "",
        "## Conversation",
        "",
    ]
    for turn in result.public_state["conversation"]:
        lines.extend(
            [
                f"### Turn {turn['turn']}: {turn['speaker']} ({turn['phase']})",
                turn["message"],
                "",
            ]
        )

    lines.extend(
        [
            "## Final Actions",
            "",
            "| Agent | Final claim | Synthetic reward |",
            "| --- | ---: | ---: |",
        ]
    )
    for provider, action in zip(result.providers, result.actions):
        lines.append(f"| {provider} | {action.get('claim')} | {result.rewards[provider]:.1f} |")
    lines.extend(
        [
            "",
            "The evaluator scores the final actions, while preserving all four visible turns in the trial record. A live-provider run follows the same transcript protocol and records provider provenance for every turn.",
            "",
        ]
    )
    return "\n".join(lines)


def save_dialogue_demo(markdown: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown, encoding="utf-8")
    return path
